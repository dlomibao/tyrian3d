/**
 * JE_textWidth (fonthand.c L102-117): a space is 6 pixels, a glyph its sprite's width plus 1.
 * Strings hold one char per CP437 byte (latin1). An empty sprite slot has width 0 (load_sprites).
 */
export function JE_textWidth(s: string, font: number): number {
  const sprites = g.res.spriteTables[font].sprites;
  let x = 0;

  for (let i = 0; i < s.length; ++i) {
    const sprite_id = fontMap[s.charCodeAt(i) & 0xff];

    if (s[i] === " ") x += 6;
    else if (sprite_id !== -1) x += (sprites[sprite_id]?.width ?? 0) + 1;
  }

  return x;
}
